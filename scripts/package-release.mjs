function loadShotcraftManifest(repoRoot) {
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(path.join(repoRoot, SHOTCRAFT_MANIFEST_FILE), 'utf8'));
  } catch {
    throw new ActionRequiredError(
      'release_shotcraft_manifest_invalid',
      'Shotcraft manifest is missing or invalid JSON.',
    );
  }
  if (manifest?.schemaVersion !== 1
    || manifest.adaptationNotice !== SHOTCRAFT_ADAPTATION_NOTICE
    || JSON.stringify(manifest.upstream) !== JSON.stringify(SHOTCRAFT_UPSTREAM)
    || manifest.stats?.cards !== 152
    || manifest.stats?.styles !== 209
    || manifest.catalog?.target !== SHOTCRAFT_CATALOG_FILE
    || manifest.attribution?.target !== SHOTCRAFT_ATTRIBUTION_FILE
    || !Array.isArray(manifest.cards)
    || manifest.cards.length !== 152) {
    throw new ActionRequiredError(
      'release_shotcraft_manifest_invalid',
      'Shotcraft manifest contract does not match the pinned catalog.',
    );
  }
  const cardTargets = [];
  const names = new Set();
  const targets = new Set([manifest.catalog.target, manifest.attribution.target]);
  for (const card of manifest.cards) {
    const expectedTarget = `${SHOTCRAFT_ROOT}/cards/${card?.category}/${card?.name}.md`;
    const expectedSource = `references/shots/${card?.category}/${card?.name}.md`;
    const expectedUpstreamUrl = `${SHOTCRAFT_UPSTREAM.repository}/blob/`
      + `${SHOTCRAFT_UPSTREAM.commit}/${expectedSource}`;
    if (!card || typeof card.name !== 'string'
      || !/^[a-z0-9][a-z0-9-]*$/u.test(card.name)
      || typeof card.category !== 'string'
      || !/^[a-z0-9][a-z0-9-]*$/u.test(card.category)
      || card.target !== expectedTarget
      || card.source !== expectedSource
      || card.upstreamUrl !== expectedUpstreamUrl
      || !Number.isSafeInteger(card.bytes) || card.bytes <= 0
      || typeof card.sha256 !== 'string' || !/^[a-f0-9]{64}$/u.test(card.sha256)
      || names.has(card.name) || targets.has(card.target)) {
      throw new ActionRequiredError(
        'release_shotcraft_manifest_invalid',
        'Shotcraft manifest contains an invalid or duplicate card entry.',
      );
    }
    names.add(card.name);
    targets.add(card.target);
    cardTargets.push(card.target);
  }
  for (const record of [manifest.catalog, manifest.attribution]) {
    if (!Number.isSafeInteger(record.bytes) || record.bytes <= 0
      || typeof record.sha256 !== 'string' || !/^[a-f0-9]{64}$/u.test(record.sha256)) {
      throw new ActionRequiredError(
        'release_shotcraft_manifest_invalid',
        'Shotcraft manifest contains an invalid catalog or attribution digest.',
      );
    }
  }
  return { manifest, cardTargets: cardTargets.toSorted() };
}

