#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  copyFileSync,
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  realpathSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const EXPECTED_UPSTREAM_COMMIT =
  "41ee360d82f4c491ba9d88a24a4add7d8ff1cf8b";
const UPSTREAM_REPOSITORY =
  "https://github.com/Vincentwei1021/video-shotcraft";
const UPSTREAM_LICENSE = "Apache-2.0";
const EXPECTED_CARD_COUNT = 152;
const EXPECTED_STYLE_COUNT = 209;
const EXPECTED_LIBRARY_REVISION = "bdd94be16d60fa8f";
const ADAPTATION_NOTICE =
  "Generated by erduo-broll-loop-engineering from the pinned video-shotcraft library metadata. Preview/media fields and demo, texture, audio, and TSX runtime assets are excluded. Copied Markdown card bodies are byte-identical to the pinned upstream sources.";

function fail(message) {
  process.stderr.write(`sync-video-shotcraft: ${message}\n`);
  process.exit(1);
}

function parseArgs(argv) {
  const result = {};
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument !== "--source" && argument !== "--destination") {
      fail(`unknown argument: ${argument}`);
    }
    const value = argv[index + 1];
    if (!value || value.startsWith("--")) {
      fail(`${argument} requires a path`);
    }
    result[argument.slice(2)] = value;
    index += 1;
  }
  if (!result.source) {
    fail("--source <video-shotcraft checkout> is required");
  }
  return result;
}

function sha256(data) {
  return createHash("sha256").update(data).digest("hex");
}

function portablePath(...parts) {
  return parts.join("/");
}

function isStrictlyWithin(parent, child) {
  const pathFromParent = relative(parent, child);
  return pathFromParent !== "" && !isAbsolute(pathFromParent)
    && pathFromParent !== ".." && !pathFromParent.startsWith(`..${sep}`);
}

function requireSafeDirectory(directory, parent, label) {
  let info;
  let canonical;
  try {
    info = lstatSync(directory);
    canonical = realpathSync(directory);
  } catch (error) {
    fail(`${label} is missing or cannot be inspected: ${error.message}`);
  }
  if (info.isSymbolicLink() || !info.isDirectory()) {
    fail(`${label} must be a real directory, not a symlink or special file`);
  }
  if (!isStrictlyWithin(parent, canonical)) {
    fail(`${label} resolves outside the destination`);
  }
  return canonical;
}

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    fail(`cannot parse ${path}: ${error.message}`);
  }
}

const args = parseArgs(process.argv.slice(2));
const sourceRoot = resolve(args.source);
const scriptRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const destinationRoot = resolve(args.destination ?? scriptRoot);
const skillRoot = join(destinationRoot, "erduo-broll-loop-engineering");
const shotcraftRoot = join(skillRoot, "references", "shotcraft");
const cardsRoot = join(shotcraftRoot, "cards");

if (!existsSync(join(sourceRoot, ".git"))) {
  fail("--source must be a Git checkout of video-shotcraft");
}
if (!existsSync(join(skillRoot, "SKILL.md"))) {
  fail("--destination must contain erduo-broll-loop-engineering/SKILL.md");
}

let canonicalDestination;
try {
  canonicalDestination = realpathSync(destinationRoot);
} catch (error) {
  fail(`cannot inspect --destination: ${error.message}`);
}
const canonicalSkillRoot = requireSafeDirectory(
  skillRoot,
  canonicalDestination,
  "destination Skill root",
);
requireSafeDirectory(
  join(skillRoot, "references"),
  canonicalSkillRoot,
  "destination references directory",
);
if (existsSync(shotcraftRoot)) {
  requireSafeDirectory(
    shotcraftRoot,
    canonicalSkillRoot,
    "destination Shotcraft directory",
  );
}

let upstreamCommit;
try {
  upstreamCommit = execFileSync("git", ["rev-parse", "HEAD"], {
    cwd: sourceRoot,
    encoding: "utf8",
  }).trim();
} catch (error) {
  fail(`cannot inspect source Git commit: ${error.message}`);
}
if (upstreamCommit !== EXPECTED_UPSTREAM_COMMIT) {
  fail(
    `source commit ${upstreamCommit} does not match pinned ${EXPECTED_UPSTREAM_COMMIT}`,
  );
}
const trackedChanges = execFileSync(
  "git",
  ["status", "--porcelain", "--untracked-files=no"],
  { cwd: sourceRoot, encoding: "utf8" },
).trim();
if (trackedChanges) {
  fail("source checkout has tracked changes; use a clean pinned checkout");
}

const libraryPath = join(sourceRoot, "gallery", "api", "library.json");
const library = readJson(libraryPath);
if (library.revision !== EXPECTED_LIBRARY_REVISION) {
  fail(
    `expected library revision ${EXPECTED_LIBRARY_REVISION}, found ${library.revision}`,
  );
}
if (!Array.isArray(library.cards)) {
  fail("gallery/api/library.json has no cards array");
}
if (library.cards.length !== EXPECTED_CARD_COUNT) {
  fail(`expected ${EXPECTED_CARD_COUNT} cards, found ${library.cards.length}`);
}

const cardNames = new Set();
const styleKeys = new Set();
const categoryCounts = new Map();
const preparedCards = [];

for (const card of library.cards) {
  if (typeof card.name !== "string" || !/^[a-z0-9][a-z0-9-]*$/.test(card.name)) {
    fail(`invalid card name: ${JSON.stringify(card.name)}`);
  }
  if (cardNames.has(card.name)) {
    fail(`duplicate card name: ${card.name}`);
  }
  cardNames.add(card.name);

  for (const field of ["summary", "use", "duration", "energy", "intention"]) {
    if (typeof card[field] !== "string" || !card[field].trim()) {
      fail(`card ${card.name} has no ${field}`);
    }
  }
  if (!Array.isArray(card.tags) || card.tags.some((tag) => typeof tag !== "string")) {
    fail(`card ${card.name} has invalid tags`);
  }

  if (typeof card.category !== "string" || !/^[a-z0-9-]+$/.test(card.category)) {
    fail(`invalid category for ${card.name}`);
  }
  if (
    typeof card.source !== "string" ||
    card.source !== `references/shots/${card.category}/${card.name}.md`
  ) {
    fail(`source is not closed for ${card.name}: ${JSON.stringify(card.source)}`);
  }

  const sourcePath = resolve(sourceRoot, ...card.source.split("/"));
  const expectedSourceRoot = resolve(sourceRoot, "references", "shots");
  if (!sourcePath.startsWith(`${expectedSourceRoot}${sep}`)) {
    fail(`source escapes references/shots for ${card.name}`);
  }
  if (!existsSync(sourcePath)) {
    fail(`missing source card: ${card.source}`);
  }

  if (!Array.isArray(card.styles) || card.styles.length === 0) {
    fail(`card ${card.name} has no styles`);
  }
  const styles = card.styles.map((style) => {
    if (typeof style.key !== "string" || !style.key) {
      fail(`card ${card.name} has a style without a key`);
    }
    if (styleKeys.has(style.key)) {
      fail(`duplicate style key: ${style.key}`);
    }
    for (const field of ["label", "description"]) {
      if (typeof style[field] !== "string" || !style[field].trim()) {
        fail(`style ${style.key} has no ${field}`);
      }
    }
    styleKeys.add(style.key);
    return {
      key: style.key,
      label: style.label,
      description: style.description,
      ...(typeof style.use === "string" ? { use: style.use } : {}),
    };
  });

  const targetRelative = portablePath("cards", card.category, `${card.name}.md`);
  const targetPath = resolve(shotcraftRoot, ...targetRelative.split("/"));
  categoryCounts.set(card.category, (categoryCounts.get(card.category) ?? 0) + 1);
  preparedCards.push({ card, styles, sourcePath, targetRelative, targetPath });
}

if (styleKeys.size !== EXPECTED_STYLE_COUNT) {
  fail(`expected ${EXPECTED_STYLE_COUNT} styles, found ${styleKeys.size}`);
}

const upstreamMarkdownSources = readdirSync(
  join(sourceRoot, "references", "shots"),
  { recursive: true },
)
  .map(String)
  .filter((entry) => entry.endsWith(".md") && entry !== "ATTRIBUTION.md")
  .map((entry) => portablePath("references", "shots", ...entry.split(sep)))
  .sort();
const catalogSources = preparedCards.map(({ card }) => card.source).sort();
if (
  upstreamMarkdownSources.length !== catalogSources.length ||
  upstreamMarkdownSources.some((source, index) => source !== catalogSources[index])
) {
  fail("library sources do not form a closed set with references/shots/*.md");
}

// This directory is generated output. Rebuild the complete tree so a dirty
// destination cannot retain unmanifested demos, media, source, or symlinks.
rmSync(shotcraftRoot, { recursive: true, force: true });
mkdirSync(cardsRoot, { recursive: true });

for (const item of preparedCards) {
  mkdirSync(dirname(item.targetPath), { recursive: true });
  copyFileSync(item.sourcePath, item.targetPath);
}

const attributionSource = join(
  sourceRoot,
  "references",
  "shots",
  "ATTRIBUTION.md",
);
if (!existsSync(attributionSource)) {
  fail("missing references/shots/ATTRIBUTION.md");
}
const attributionTarget = join(shotcraftRoot, "upstream-attribution.md");
mkdirSync(shotcraftRoot, { recursive: true });
copyFileSync(attributionSource, attributionTarget);

const categories = [...categoryCounts.entries()]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([name, cards]) => ({ name, cards }));

const catalog = {
  schemaVersion: 1,
  adaptationNotice: ADAPTATION_NOTICE,
  upstream: {
    repository: UPSTREAM_REPOSITORY,
    commit: upstreamCommit,
    libraryRevision: library.revision,
    license: UPSTREAM_LICENSE,
  },
  stats: {
    cards: preparedCards.length,
    styles: styleKeys.size,
    categories,
  },
  cards: preparedCards.map(({ card, styles, targetRelative }) => ({
    name: card.name,
    summary: card.summary,
    use: card.use,
    duration: card.duration,
    energy: card.energy,
    intention: card.intention,
    category: card.category,
    tags: card.tags,
    styles,
    source: card.source,
    upstreamUrl: `${UPSTREAM_REPOSITORY}/blob/${upstreamCommit}/${card.source}`,
    localSource: targetRelative,
  })),
};
const catalogText = `${JSON.stringify(catalog, null, 2)}\n`;
const catalogPath = join(shotcraftRoot, "catalog.json");
writeFileSync(catalogPath, catalogText);

const cards = preparedCards.map(({ card, targetRelative, targetPath }) => {
  const data = readFileSync(targetPath);
  return {
    name: card.name,
    category: card.category,
    source: card.source,
    upstreamUrl: `${UPSTREAM_REPOSITORY}/blob/${upstreamCommit}/${card.source}`,
    target: portablePath(
      "erduo-broll-loop-engineering",
      "references",
      "shotcraft",
      targetRelative,
    ),
    bytes: statSync(targetPath).size,
    sha256: sha256(data),
  };
});
const attributionData = readFileSync(attributionTarget);
const manifest = {
  schemaVersion: 1,
  adaptationNotice: ADAPTATION_NOTICE,
  upstream: {
    repository: UPSTREAM_REPOSITORY,
    commit: upstreamCommit,
    libraryRevision: library.revision,
    license: UPSTREAM_LICENSE,
  },
  stats: {
    cards: cards.length,
    styles: styleKeys.size,
  },
  catalog: {
    target: "erduo-broll-loop-engineering/references/shotcraft/catalog.json",
    bytes: Buffer.byteLength(catalogText),
    sha256: sha256(catalogText),
  },
  attribution: {
    source: "references/shots/ATTRIBUTION.md",
    target:
      "erduo-broll-loop-engineering/references/shotcraft/upstream-attribution.md",
    bytes: attributionData.length,
    sha256: sha256(attributionData),
  },
  cards,
};
writeFileSync(
  join(shotcraftRoot, "manifest.json"),
  `${JSON.stringify(manifest, null, 2)}\n`,
);

process.stdout.write(
  `${JSON.stringify({
    status: "synced",
    cards: cards.length,
    styles: styleKeys.size,
    categories: categories.length,
    commit: upstreamCommit,
    libraryRevision: library.revision,
  })}\n`,
);
