#!/usr/bin/env node

import { readFileSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { realpathSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const skillRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceFile = path.join(skillRoot, 'references', 'roles', 'role-charters.json');
const source = JSON.parse(readFileSync(sourceFile, 'utf8'));

const roleTargets = Object.freeze({
  director: [
    'stages/broll-director/AGENTS.md',
    'stages/broll-director/CLAUDE.md',
    'stages/broll-director/role-prompt.md',
  ],
  lead: [
    'stages/broll-master-build/role-prompts/lead.md',
    'stages/broll-remotion-build/role-prompts/lead.md',
  ],
  builder: [
    'stages/broll-master-build/role-prompts/builder.md',
    'stages/broll-remotion-build/role-prompts/builder.md',
  ],
});

function requireRole(role) {
  const charter = source.roles?.[role];
  if (!charter) throw new Error(`unknown role ${JSON.stringify(role)}`);
  if (!Array.isArray(charter.executionAnchor) || charter.executionAnchor.length > 8) {
    throw new Error(`${role} execution anchor must contain at most 8 lines`);
  }
  return charter;
}

function positiveCraftAnchor() {
  if (!Array.isArray(source.positiveCraftAnchor) || source.positiveCraftAnchor.length !== 12) {
    throw new Error('positive craft anchor must contain exactly 12 principles');
  }
  return source.positiveCraftAnchor;
}

function renderPrompt(role) {
  const charter = requireRole(role);
  return [
    `# ${charter.title}`,
    '',
    'These rules are injected. Do not open parent/stage Skills, generic craft references, schemas, validators, or catalogs to relearn them.',
    '',
    ...charter.rules.map((rule, index) => `${index + 1}. ${rule}`),
    '',
    '## Positive twelve-principle anchor',
    '',
    ...positiveCraftAnchor().map((line) => `- ${line}`),
    '',
    '## Source-authoring anchor',
    '',
    ...charter.executionAnchor.map((line) => `- ${line}`),
    '',
    '## Compression recovery fields',
    '',
    charter.recoveryFields.map((field) => `\`${field}\``).join(', '),
    '',
  ].join('\n');
}

function renderInheritance(roles) {
  return [
    '<!-- Generated by scripts/generate-role-files.mjs. Do not edit this file directly. -->',
    '',
    ...roles.flatMap((role) => [renderPrompt(role).trimEnd(), '']),
  ].join('\n');
}

function renderAssignmentSelectedInheritance() {
  return [
    '<!-- Generated by scripts/generate-role-files.mjs. Do not edit this file directly. -->',
    '',
    '# Assignment-selected role charter',
    '',
    "Use only the assignment packet's exact `rolePrompt`, `executionAnchor`, and",
    '`recoveryFields`. The packet selects either Lead or Builder. This inherited',
    'file intentionally injects neither role so both charters can never apply to one',
    'Agent at the same time.',
    '',
  ].join('\n');
}

export function roleInjection(role) {
  const charter = requireRole(role);
  return Object.freeze({
    rolePrompt: renderPrompt(role),
    positiveCraftAnchor: Object.freeze([...positiveCraftAnchor()]),
    executionAnchor: Object.freeze([...charter.executionAnchor]),
    recoveryFields: Object.freeze([...charter.recoveryFields]),
  });
}

export function generatedRoleFiles() {
  const files = new Map();
  for (const [role, targets] of Object.entries(roleTargets)) {
    for (const target of targets) files.set(target, renderPrompt(role));
  }
  const builderInheritance = renderAssignmentSelectedInheritance();
  for (const stage of ['broll-master-build', 'broll-remotion-build']) {
    files.set(`stages/${stage}/AGENTS.md`, builderInheritance);
    files.set(`stages/${stage}/CLAUDE.md`, builderInheritance);
  }
  files.set('stages/broll-director/AGENTS.md', renderInheritance(['director']));
  files.set('stages/broll-director/CLAUDE.md', renderInheritance(['director']));
  return files;
}

export async function syncRoleFiles({ check = false } = {}) {
  const drift = [];
  for (const [relative, expected] of generatedRoleFiles()) {
    const file = path.join(skillRoot, relative);
    if (check) {
      let actual = null;
      try { actual = await readFile(file, 'utf8'); } catch {}
      if (actual !== expected) drift.push(relative);
    } else {
      await writeFile(file, expected, 'utf8');
    }
  }
  if (drift.length > 0) throw new Error(`generated role files are stale: ${drift.join(', ')}`);
  return { status: check ? 'current' : 'generated', files: generatedRoleFiles().size };
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args[0] && args[0] !== '--check')) {
    throw new Error('usage: generate-role-files.mjs [--check]');
  }
  const result = await syncRoleFiles({ check: args[0] === '--check' });
  process.stdout.write(`${JSON.stringify(result)}\n`);
}

if (process.argv[1]
  && realpathSync(path.resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url))) {
  main().catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  });
}
