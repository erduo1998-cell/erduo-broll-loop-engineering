function loadShotcraftRemotionManifest(repoRoot) {
  let manifest;
  try {
    const manifestBody = readFileSync(path.join(repoRoot, SHOTCRAFT_REMOTION_MANIFEST_FILE));
    const manifestDigest = createHash('sha256').update(manifestBody).digest('hex');
    if (manifestDigest !== SHOTCRAFT_REMOTION_MANIFEST_SHA256) {
      throw new Error('pinned manifest digest mismatch');
    }
    manifest = JSON.parse(manifestBody.toString('utf8'));
  } catch {
    throw new ActionRequiredError(
      'release_shotcraft_remotion_manifest_invalid',
      'Shotcraft Remotion source manifest is missing or invalid JSON.',
    );
  }
  const repository = SHOTCRAFT_UPSTREAM.repository;
  const commit = SHOTCRAFT_UPSTREAM.commit;
  if (manifest?.schemaVersion !== 1
    || manifest.upstream?.repository !== repository
    || manifest.upstream?.commit !== commit
    || manifest.upstream?.license !== SHOTCRAFT_UPSTREAM.license
    || manifest.stats?.cards !== 152
    || !Number.isSafeInteger(manifest.stats?.sourceFiles)
    || manifest.stats.sourceFiles <= 0
    || !Array.isArray(manifest.files)
    || manifest.files.length !== manifest.stats.sourceFiles) {
    throw new ActionRequiredError(
      'release_shotcraft_remotion_manifest_invalid',
      'Shotcraft Remotion source manifest does not match its pinned source.',
    );
  }
  const fixed = [manifest.index, manifest.sourceDescription];
  const records = [...fixed, ...manifest.files];
  const targets = new Set();
  const sources = new Set();
  for (const record of records) {
    const target = record?.target;
    const relative = typeof target === 'string'
      ? path.relative(SHOTCRAFT_REMOTION_ROOT, target)
      : null;
    if (!record || typeof target !== 'string'
      || path.isAbsolute(target) || target.includes('\\')
      || !relative || path.isAbsolute(relative) || relative === '..'
      || relative.startsWith(`..${path.sep}`)
      || !Number.isSafeInteger(record.bytes) || record.bytes <= 0
      || typeof record.sha256 !== 'string' || !/^[a-f0-9]{64}$/u.test(record.sha256)
      || targets.has(target)) {
      throw new ActionRequiredError(
        'release_shotcraft_remotion_manifest_invalid',
        'Shotcraft Remotion manifest contains an invalid or duplicate target.',
      );
    }
    targets.add(target);
  }
  if (manifest.index.target !== `${SHOTCRAFT_REMOTION_ROOT}/index.json`
    || manifest.sourceDescription.target !== `${SHOTCRAFT_REMOTION_ROOT}/SOURCE.md`) {
    throw new ActionRequiredError(
      'release_shotcraft_remotion_manifest_invalid',
      'Shotcraft Remotion manifest metadata targets are invalid.',
    );
  }
  for (const record of manifest.files) {
    const expectedTarget = `${SHOTCRAFT_REMOTION_ROOT}/${record.source}`;
    const expectedUrl = `${repository}/blob/${commit}/${record.source}`;
    if (typeof record.source !== 'string' || path.isAbsolute(record.source)
      || record.source.includes('\\') || record.source.startsWith('../')
      || record.target !== expectedTarget || record.upstreamUrl !== expectedUrl
      || sources.has(record.source)) {
      throw new ActionRequiredError(
        'release_shotcraft_remotion_manifest_invalid',
        'Shotcraft Remotion manifest contains an invalid or duplicate source.',
      );
    }
    sources.add(record.source);
  }
  return {
    manifest,
    records,
    releaseFiles: [SHOTCRAFT_REMOTION_MANIFEST_FILE, ...targets].toSorted(),
  };
}

